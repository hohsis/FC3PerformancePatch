"""Compiles the in-game menu's two shaders and writes src/menu_shaders.h.

The menu must not depend on a shader compiler being present where the game
runs (under Wine/Proton there may be none that loads), so the compiled code
is part of the source tree. Run this on Windows after changing the HLSL
below; it uses the system's d3dcompiler_47.dll.

    python tools/gen_menu_shaders.py
"""
import ctypes
import os
import sys

SOURCE = """\
struct VI { float2 p : POSITION; float2 uv : TEXCOORD0; float4 c : COLOR0; };
struct PI { float4 p : SV_POSITION; float2 uv : TEXCOORD0; float4 c : COLOR0; };
Texture2D font_texture : register(t0);
SamplerState font_sampler : register(s0);
PI vs_main(VI i) { PI o; o.p = float4(i.p, 0.0, 1.0); o.uv = i.uv; o.c = i.c; return o; }
float4 ps_main(PI i) : SV_Target { return float4(i.c.rgb, i.c.a * font_texture.Sample(font_sampler, i.uv).r); }
"""

D3DCOMPILE_OPTIMIZATION_LEVEL3 = 1 << 15
D3DCOMPILER_STRIP_REFLECTION_DATA = 1
D3DCOMPILER_STRIP_DEBUG_INFO = 2
D3DCOMPILER_STRIP_TEST_BLOBS = 4


def blob_bytes(blob):
    vtbl = ctypes.cast(blob, ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
    get_pointer = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(vtbl[3])
    get_size = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vtbl[4])
    release = ctypes.WINFUNCTYPE(ctypes.c_ulong, ctypes.c_void_p)(vtbl[2])
    data = ctypes.string_at(get_pointer(blob), get_size(blob))
    release(blob)
    return data


def compile_shader(dll, entry, target):
    source = SOURCE.encode("ascii")
    code, errors = ctypes.c_void_p(), ctypes.c_void_p()
    dll.D3DCompile.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.c_void_p, ctypes.c_void_p,
                               ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint, ctypes.c_uint,
                               ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p)]
    dll.D3DCompile.restype = ctypes.c_long
    hr = dll.D3DCompile(source, len(source), b"fc3pp_menu", None, None, entry, target,
                        D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, ctypes.byref(code), ctypes.byref(errors))
    if hr < 0 or not code:
        message = blob_bytes(errors).decode("ascii", "replace") if errors else ""
        raise SystemExit("D3DCompile(%s) failed: 0x%08X %s" % (entry.decode(), hr & 0xFFFFFFFF, message))
    data = blob_bytes(code)
    # Reflection and debug data are not needed to run the shader; the input
    # signature, which the input layout is checked against, stays.
    stripped = ctypes.c_void_p()
    dll.D3DStripShader.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_uint, ctypes.POINTER(ctypes.c_void_p)]
    dll.D3DStripShader.restype = ctypes.c_long
    flags = D3DCOMPILER_STRIP_REFLECTION_DATA | D3DCOMPILER_STRIP_DEBUG_INFO | D3DCOMPILER_STRIP_TEST_BLOBS
    if dll.D3DStripShader(data, len(data), flags, ctypes.byref(stripped)) >= 0 and stripped:
        data = blob_bytes(stripped)
    return data


def c_array(name, data):
    lines = ["static const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    if os.name != "nt":
        raise SystemExit("this needs Windows (d3dcompiler_47.dll)")
    dll = ctypes.WinDLL("d3dcompiler_47.dll")
    vs = compile_shader(dll, b"vs_main", b"vs_4_0")
    ps = compile_shader(dll, b"ps_main", b"ps_4_0")
    out = [
        "/* The in-game menu's shaders, compiled. GENERATED by tools/gen_menu_shaders.py;",
        " * do not edit by hand. Compiled code is kept in the source tree so that the",
        " * menu needs no shader compiler where the game runs.",
        " *",
        " * The source (HLSL, Direct3D feature level 10.0 and up):",
        " *",
    ]
    out += [" *     " + line for line in SOURCE.splitlines()]
    out += [
        " *",
        " * SPDX-License-Identifier: GPL-3.0-or-later",
        " */",
        "#ifndef FC3PP_MENU_SHADERS_H",
        "#define FC3PP_MENU_SHADERS_H",
        "",
        c_array("MENU_VS_CODE", vs),
        "",
        c_array("MENU_PS_CODE", ps),
        "",
        "#endif /* FC3PP_MENU_SHADERS_H */",
        "",
    ]
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "menu_shaders.h")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out))
    print("vertex shader %d bytes, pixel shader %d bytes" % (len(vs), len(ps)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
